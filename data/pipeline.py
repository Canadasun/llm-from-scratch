"""Phase 2 data gate: licence allowlist, quality filters, secret scrubbing,
near-duplicate removal and repository-level splits.

Every filter returns a reason string on rejection so the source manifest can
record exactly why each row was dropped.
"""

import ast
import hashlib
import re
import zlib
from collections import Counter

import numpy as np

from safety.scrub import scrub_secrets

ALLOWED_LICENCES = frozenset({"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "PSF-2.0"})
_LICENCE_ALIASES = {
    "mit": "MIT", "mit license": "MIT", "expat": "MIT",
    "apache-2.0": "Apache-2.0", "apache 2.0": "Apache-2.0", "apache license 2.0": "Apache-2.0",
    "apache-2": "Apache-2.0", "apache2": "Apache-2.0",
    "bsd-2-clause": "BSD-2-Clause", "bsd 2-clause": "BSD-2-Clause", "bsd-2": "BSD-2-Clause",
    "bsd-3-clause": "BSD-3-Clause", "bsd 3-clause": "BSD-3-Clause", "bsd-3": "BSD-3-Clause",
    "isc": "ISC", "isc license": "ISC",
    "psf-2.0": "PSF-2.0", "python-2.0": "PSF-2.0", "psf": "PSF-2.0",
}


def normalize_licence(value):
    if not isinstance(value, str):
        return None
    return _LICENCE_ALIASES.get(value.strip().lower())


def licence_decision(licences):
    if isinstance(licences, str):
        licences = [licences]
    licences = [x for x in (licences or []) if x is not None]
    if not licences:
        return None, "licence-missing"
    normalized = [normalize_licence(x) for x in licences]
    if any(n is None or n not in ALLOWED_LICENCES for n in normalized):
        return None, "licence-not-allowlisted"
    return sorted(set(normalized)), None


def python_parse_reason(source, max_bytes=256 * 1024):
    if len(source.encode("utf-8", errors="replace")) > max_bytes:
        return "too-large"
    try:
        ast.parse(source)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        return "python-parse-failed"
    return None


_GENERATED_MARKERS = re.compile(
    r"auto-?generated (?:file|code|by)|automatically generated|do not edit|@generated"
    r"|generated by (?:the )?(?:protocol buffer|protoc|swig|cython|thrift|grpc|django \d|pyuic|openapi|"
    r"swagger|sphinx-apidoc|setuptools|versioneer|alembic)|code generated by", re.IGNORECASE)


def generated_reason(source):
    head = source[:2048]
    if _GENERATED_MARKERS.search(head):
        return "generated-marker"
    lines = source.splitlines() or [""]
    if max(len(line) for line in lines) > 1000:
        return "minified-long-line"
    if sum(len(line) for line in lines) / len(lines) > 100:
        return "minified-mean-line"
    alnum = sum(c.isalnum() for c in source)
    if source and alnum / len(source) < 0.25:
        return "low-alphanumeric"
    data_lines = sum(1 for line in lines if re.fullmatch(r"\s*[-+0-9.,xXa-fA-F'\"\[\](){}: ]+,?\s*", line or "x"))
    if len(lines) >= 50 and data_lines / len(lines) > 0.5:
        return "data-literal"
    return None


def _all(*patterns, flags=re.I):
    compiled = [re.compile(p, flags) for p in patterns]
    return lambda s: all(c.search(s) for c in compiled)


_PAYLOAD_RULES = [
    ("keylogger", _all(r"\bkey\s*_?logg?er\b")),
    ("keylogger", _all(r"pynput\.keyboard", r"smtplib|requests\.post|webhook")),
    ("ransomware", _all(r"\bransom(?:ware)?\b|your files (?:have been|are) encrypted")),
    ("credential-stealer", _all(r"\b(?:token|password|cookie|credential)s?\s*(?:grabber|stealer|harvest)")),
    ("browser-credential-theft", _all(r"Login Data|Local State", r"os_crypt|CryptUnprotectData|win32crypt")),
    ("discord-token-grab", _all(r"discord(?:app)?\.com/api/webhooks", r"\btoken\b|password", r"leveldb|appdata|Local Storage")),
    ("obfuscated-exec", _all(r"exec\s*\(\s*(?:base64\.b64decode|zlib\.decompress|marshal\.loads|bytes\.fromhex|codecs\.decode)")),
    ("reverse-shell", _all(r"socket\.socket\(", r"\.dup2\(", r"pty\.spawn\(|/bin/(?:ba)?sh|cmd\.exe")),
]


def payload_reason(source):
    for name, rule in _PAYLOAD_RULES:
        if rule(source):
            return f"payload-{name}"
    return None


def scrub(source):
    text, counts = scrub_secrets(source)
    return text, dict(counts)


def content_key(source):
    normalized = re.sub(r"\s+", " ", source).strip()
    return hashlib.sha256(normalized.encode("utf-8", errors="replace")).hexdigest()


def split_for_group(group, val_fraction=0.01, test_fraction=0.01):
    digest = hashlib.sha256(str(group).encode("utf-8")).digest()
    x = int.from_bytes(digest[:8], "big") / 2**64
    if x < test_fraction:
        return "test"
    if x < test_fraction + val_fraction:
        return "val"
    return "train"


_TOKEN = re.compile(r"\w+")
_PRIME = (1 << 31) - 1


class NearDuplicateIndex:
    def __init__(self, num_perm=128, bands=16, threshold=0.8, shingle=5, seed=1337):
        if num_perm % bands:
            raise ValueError("num_perm must be divisible by bands")
        rng = np.random.default_rng(seed)
        self.a = rng.integers(1, _PRIME, size=num_perm, dtype=np.uint64)
        self.b = rng.integers(0, _PRIME, size=num_perm, dtype=np.uint64)
        self.bands, self.rows = bands, num_perm // bands
        self.threshold, self.shingle = threshold, shingle
        self.buckets = [dict() for _ in range(bands)]
        self.signatures = []

    def signature(self, text):
        tokens = _TOKEN.findall(text)
        if len(tokens) < self.shingle:
            tokens = tokens + [""] * (self.shingle - len(tokens))
        shingles = {" ".join(tokens[i:i + self.shingle]) for i in range(len(tokens) - self.shingle + 1)}
        x = np.fromiter((zlib.crc32(s.encode("utf-8", errors="replace")) for s in shingles),
                        dtype=np.uint64, count=len(shingles)) % np.uint64(_PRIME)
        return ((np.outer(x, self.a) + self.b) % np.uint64(_PRIME)).min(axis=0).astype(np.uint32)

    def add_if_new(self, text=None, signature=None):
        sig = signature if signature is not None else self.signature(text)
        keys = [sig[i * self.rows:(i + 1) * self.rows].tobytes() for i in range(self.bands)]
        candidates = set()
        for band, key in enumerate(keys):
            candidates.update(self.buckets[band].get(key, ()))
        for c in candidates:
            if float(np.mean(self.signatures[c] == sig)) >= self.threshold:
                return False, c
        index = len(self.signatures)
        self.signatures.append(sig)
        for band, key in enumerate(keys):
            self.buckets[band].setdefault(key, []).append(index)
        return True, None


class SourceStats:
    def __init__(self, name):
        self.name = name
        self.rows_in = 0
        self.rows_out = 0
        self.bytes_out = 0
        self.dropped = Counter()
        self.scrubbed = Counter()
        self.splits = Counter()
        self.licences = Counter()

    def to_dict(self):
        return {"name": self.name, "rows_in": self.rows_in, "rows_out": self.rows_out,
                "bytes_out": self.bytes_out, "dropped": dict(sorted(self.dropped.items())),
                "scrubbed": dict(sorted(self.scrubbed.items())), "splits": dict(sorted(self.splits.items())),
                "licences": dict(sorted(self.licences.items()))}


def prefilter(source, licences, require_python=True, near_dup=None):
    kept, reason = licence_decision(licences)
    if reason is None and require_python:
        reason = python_parse_reason(source)
    if reason is None:
        reason = generated_reason(source) or payload_reason(source)
    if reason is not None:
        return {"reason": reason}
    text, counts = scrub(source)
    out = {"text": text, "licences": kept, "scrubbed": counts, "key": content_key(source)}
    if near_dup is not None:
        out["signature"] = near_dup.signature(source)
    return out


_WORD = re.compile(r"[A-Za-z_][A-Za-z0-9_]*|\d+")


def ngrams(text, n=13):
    words = [w.lower() for w in _WORD.findall(text)]
    return {" ".join(words[i:i + n]) for i in range(len(words) - n + 1)}


class ContaminationIndex:
    def __init__(self, texts, n=13):
        self.n = n
        self.grams = set()
        for text in texts:
            self.grams |= ngrams(text, n)

    def hits(self, text):
        return len(ngrams(text, self.n) & self.grams) if self.grams else 0


class CodeGate:
    def __init__(self, near_dup=None, exact=None, require_python=True):
        self.near_dup = near_dup or NearDuplicateIndex()
        self.exact = exact if exact is not None else set()
        self.require_python = require_python

    def check(self, source, licences, stats):
        stats.rows_in += 1
        kept, reason = licence_decision(licences)
        if reason is None and self.require_python:
            reason = python_parse_reason(source)
        if reason is None:
            reason = generated_reason(source) or payload_reason(source)
        if reason is None:
            key = content_key(source)
            if key in self.exact:
                reason = "exact-duplicate"
            else:
                self.exact.add(key)
        if reason is None:
            new, _ = self.near_dup.add_if_new(source)
            if not new:
                reason = "near-duplicate"
        if reason is not None:
            stats.dropped[reason] += 1
            return None
        text, counts = scrub(source)
        for k, v in counts.items():
            stats.scrubbed[k] += v
        for lic in kept:
            stats.licences[lic] += 1
        stats.rows_out += 1
        stats.bytes_out += len(text.encode("utf-8"))
        return text
