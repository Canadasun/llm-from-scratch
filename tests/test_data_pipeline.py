def test_pretokenizer_is_lossless_and_code_aware():
    chunks = pretokenize("def foo_bar(x1, y):\n    return x1 + 1234567\n\tpass")
    assert chunks[:4] == ["def", " foo_bar", "(", "x1"]
    assert "    " in chunks and " 123" in chunks and "456" in chunks
    rng = random.Random(0)
    alphabet = "ab_1 \t\n\r(){}é漢\x00-+#'\""
    for _ in range(3000):
        s = "".join(rng.choice(alphabet) for _ in range(rng.randint(0, 50)))
        assert "".join(pretokenize(s)) == s


def test_code_bpe_trains_incrementally_round_trips_and_serializes():
    text = CODE * 40
    tok = tokenization.build_with_specials("bpe_code", text, vocab_size=600, bpe_train_chars=len(text))
    assert tok.vocab_size <= 600 and tok.special_id(ENDOFTEXT) == tok.vocab_size - 3
    held = CODE.replace("Counter", "Tally").replace("amount", "step")
    ids = tok.encode(held)
    assert tok.decode(ids) == held
    assert len(held.encode()) / len(ids) > 3
    back = tokenization.from_dict(json.loads(json.dumps(tok.to_dict(), sort_keys=True)))
    assert back.encode(held) == ids and back.to_dict() == tok.to_dict()
    turn = f"{USER}add a and b{ASSISTANT}def add(a, b):\n    return a + b{ENDOFTEXT}"
    assert tok.decode(tok.encode(turn, allowed_special="all")) == turn
    assert not set(tok.encode("<|endoftext|>")) & tok.special_ids


def test_code_bpe_matches_naive_greedy_merge_order():
    text = "aaaa bbbb aaaa abab " * 20
    tok = CodeBPETokenizer().train(text, vocab_size=270)
    for word in ("aaaa", "abab", "bbbb", "aab"):
        ids = list(word.encode())
        while True:
            pairs = [(tok.merges[p], i) for i, p in enumerate(zip(ids, ids[1:])) if p in tok.merges]
            if not pairs:
                break
            rank = min(pairs)[0]
            pair = next(p for p, r in tok.merges.items() if r == rank)
            out, i = [], 0
            while i < len(ids):
                if i + 1 < len(ids) and (ids[i], ids[i + 1]) == pair:
                    out.append(rank)
                    i += 2
                else:
                    out.append(ids[i])
                    i += 1
            ids = out
        assert tok._encode_chunk(word) == ids


def test_code_bpe_rejects_malformed_dicts():
    with pytest.raises(ValueError):
        CodeBPETokenizer.from_dict({"kind": "bpe_code", "pattern_version": 99, "merges": []})
    with pytest.raises(ValueError):
        CodeBPETokenizer.from_dict({"kind": "bpe_code", "pattern_version": 1, "merges": [[1, 2, 300]]})
    with pytest.raises(ValueError):
        CodeBPETokenizer.from_dict({"kind": "bpe_code", "pattern_version": 1, "merges": [[256, 2, 256]]})


